import '../../domain/entities/user_entity.dart';

class UserModel extends UserEntity {
  const UserModel({
    required super.id,
    required super.uuid,
    required super.nom,
    required super.prenom,
    required super.email,
    required super.pays,
    required super.createdAt,
    required super.updatedAt,
    required super.username,
    required super.slug,
    required super.telephone,
    required super.birthyear,
    required super.noms,
    required super.photoUrl,
    required super.profilBannerUrl,
    super.gender,
    super.city,
    super.whatsapp,
    super.postalCode,
    super.neighborhood,
    super.street,
    super.monetaryZone,
    super.image,
    super.status,
    super.emailVerifiedAt,
    super.certifiedAt,
    super.deletedAt,
    super.lawManagementCompany,
    super.ipi,
    super.description,
    super.facebook,
    super.instagram,
    super.twitter,
    super.youtube,
    super.soundCloud,
    super.tiktok,
    super.snapchat,
    super.authUserFollow,
  });

  factory UserModel.fromJson(Map<String, dynamic> json) {
    return UserModel(
      id: json['id'],
      uuid: json['uuid'],
      nom: json['nom'],
      prenom: json['prenom'],
      email: json['email'],
      pays: json['pays'],
      username: json['username'],
      slug: json['slug'],
      telephone: json['telephone'],
      city: json['city'],
      whatsapp: json['whatsapp'],
      postalCode: json['postal_code'],
      neighborhood: json['neighborhood'],
      street: json['street'],
      birthyear: json['birthyear'],
      gender: json['gender'],
      noms: json['noms'],
      photoUrl: json['photo_url'],
      profilBannerUrl: json['profil_banner_url'],
      createdAt: DateTime.tryParse(json['created_at'] ?? ''),
      updatedAt: DateTime.tryParse(json['updated_at'] ?? ''),
      monetaryZone: json['monetary_zone'] != null
          ? MonetaryZone.fromJson(json['monetary_zone'])
          : null,
      image: json['image'],
      status: json['status'],
      emailVerifiedAt:
          DateTime.tryParse(json['email_verified_at'] ?? ''),
      certifiedAt: DateTime.tryParse(json['certified_at'] ?? ''),
      deletedAt: DateTime.tryParse(json['deleted_at'] ?? ''),
      lawManagementCompany: json['law_management_company'],
      ipi: json['ipi'],
      description: json['description'],
      facebook: json['facebook'],
      instagram: json['instagram'],
      twitter: json['twitter'],
      youtube: json['youtube'],
      soundCloud: json['sound_cloud'],
      tiktok: json['tiktok'],
      snapchat: json['snapchat'],
      authUserFollow: json['auth_user_follow'],
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'uuid': uuid,
      'nom': nom,
      'prenom': prenom,
      'email': email,
      'pays': pays,
      'created_at': createdAt?.toIso8601String(),
      'updated_at': updatedAt?.toIso8601String(),
      'username': username,
      'slug': slug,
      'telephone': telephone,
      'city': city,
      'whatsapp': whatsapp,
      'postal_code': postalCode,
      'neighborhood': neighborhood,
      'street': street,
      'birthyear': birthyear,
      'gender': gender,
      'noms': noms,
      'photo_url': photoUrl,
      'profil_banner_url': profilBannerUrl,
      'monetary_zone': monetaryZone?.toJson(),
      'image': image,
      'status': status,
      'email_verified_at': emailVerifiedAt?.toIso8601String(),
      'certified_at': certifiedAt?.toIso8601String(),
      'deleted_at': deletedAt?.toIso8601String(),
      'law_management_company': lawManagementCompany,
      'ipi': ipi,
      'description': description,
      'facebook': facebook,
      'instagram': instagram,
      'twitter': twitter,
      'youtube': youtube,
      'sound_cloud': soundCloud,
      'tiktok': tiktok,
      'snapchat': snapchat,
      'auth_user_follow': authUserFollow,
    };
  }
}
